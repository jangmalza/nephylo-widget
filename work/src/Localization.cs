        internal static string Text(string text) { return English ? Translate(text,0) : text; }
        private static string Translate(string text, int depth)
        {
            if (String.IsNullOrEmpty(text) || depth > 12) return text;
            string exact;
            if (EnglishText.TryGetValue(text,out exact)) return exact;
            if (text.Trim() != text) {
                string trimmed = text.Trim();
                if (trimmed.Length == 0) return text;
                int leading = text.Length - text.TrimStart().Length, trailing = text.Length - text.TrimEnd().Length;
                return text.Substring(0,leading) + Translate(trimmed,depth+1) + text.Substring(text.Length-trailing);
            }
            foreach (var template in Templates) {
                var match = template.Pattern.Match(text);
                if (!match.Success) continue;
                var values = new object[match.Groups.Count - 1];
                for (int i=1;i<match.Groups.Count;i++) values[i-1] = template.TranslateCapture ? Translate(match.Groups[i].Value,depth+1) : match.Groups[i].Value;
                return String.Format(CultureInfo.InvariantCulture,template.English,values);
            }
            // Only split explicit UI sentence/section separators, never replace arbitrary words.
            foreach (var separator in new[] { "\n", " · " }) {
                if (text.IndexOf(separator,StringComparison.Ordinal) >= 0) {
                    var parts = text.Split(new[] { separator },StringSplitOptions.None);
                    for (int i=0;i<parts.Length;i++) parts[i] = Translate(parts[i],depth+1);
                    return String.Join(separator,parts);
                }
            }
            return text;
        }
